# ---------------------------------------------------------------- latency matching (Task 4)
TOL = 0.2
def match_clip(c):
    ex, fin = c["expected_detail"], c["final_times_s"]
    F = [e["end"] + (0 if e.get("forced") else HANG) for e in ex]
    taken, pairs, extra = {}, [], []
    for i, f in enumerate(fin):
        ks = [k for k in range(len(ex)) if F[k] - TOL <= f]
        if not ks:
            extra.append(dict(final_index=i, time=f, reason="final before first expected flush time")); continue
        k = ks[-1]
        if k in taken:
            extra.append(dict(final_index=i, time=f, reason=f"second final in window of expected {k} (already matched to final {taken[k]})")); continue
        taken[k] = i; pairs.append((k, i))
    unmatched_exp = [dict(expected_index=k, start=ex[k]["start"], end=ex[k]["end"], forced=ex[k].get("forced")) for k in range(len(ex)) if k not in taken]
    return F, pairs, extra, unmatched_exp

lat = dict(old=dict(ttfw=[], fin=[]), corrected=dict(ttfw=[], fin_after_flush=[], fin_after_end=[]), mismatch_old=dict(ttfw=[], fin=[]), mismatch_corr=dict(ttfw=[], fin_after_flush=[]))
audit = []
for c in BASE["clips"]:
    ex, fin, tt = c["expected_detail"], c["final_times_s"], c["ttfw_s"]
    F, pairs, extra, unm = match_clip(c)
    idx_same = all(k == i for k, i in pairs) and len(pairs) == len(fin) == len(ex)
    mism = c["finals_received"] != c["utterances_expected"]
    # first-message time per old group i (only exists for i < len(expected))
    mfirst = {i: tt[i] + ex[i]["start"] for i in range(min(len(tt), len(ex)))}
    pair_rows = []
    for k, i in pairs:
        row = dict(expected_index=k, final_index=i, old_index_pair=(k == i), flush_ref_s=round(F[k], 3), final_time_s=fin[i],
                   final_after_end_s=round(fin[i] - ex[k]["end"], 3), final_after_flush_s=round(fin[i] - F[k], 3))
        m = mfirst.get(i)
        if m is None:
            row["ttfw_s"] = None; row["ttfw_note"] = "first-message time of this group not stored (final index beyond expected count)"
        elif m < ex[k]["start"] - TOL:
            row["ttfw_s"] = None; row["ttfw_note"] = "first message precedes expected start: index grouping inconsistent"
        elif m > fin[i] + 0.01:
            row["ttfw_s"] = None; row["ttfw_note"] = "first message after final: inconsistent"
        else:
            row["ttfw_s"] = round(m - ex[k]["start"], 3)
        pair_rows.append(row)
        lat["corrected"]["fin_after_end"].append(row["final_after_end_s"])
        lat["corrected"]["fin_after_flush"].append(row["final_after_flush_s"])
        if row["ttfw_s"] is not None:
            lat["corrected"]["ttfw"].append(row["ttfw_s"])
        if mism and row["ttfw_s"] is not None:
            lat["mismatch_corr"]["ttfw"].append(row["ttfw_s"])
        if mism:
            lat["mismatch_corr"]["fin_after_flush"].append(row["final_after_flush_s"])
    lat["old"]["ttfw"] += c["ttfw_s"]; lat["old"]["fin"] += c["final_latency_s"]
    if mism:
        lat["mismatch_old"]["ttfw"] += c["ttfw_s"]; lat["mismatch_old"]["fin"] += c["final_latency_s"]
    audit.append(dict(id=c["id"], expected=len(ex), finals=len(fin), mismatch=mism, index_pairing_equals_timestamp_pairing=idx_same,
                      expected_detail=ex, final_times_s=fin, final_words=c["final_words"], old_ttfw=c["ttfw_s"],
                      old_final_latency_s=c["final_latency_s"], pairs=pair_rows, unmatched_expected=unm, extra_finals=extra))

def dist(v):
    v = np.array(v, float)
    return dict(n=len(v), p50=round(float(np.percentile(v, 50)), 3), p95=round(float(np.percentile(v, 95)), 3), max=round(float(v.max()), 3), mean=round(float(v.mean()), 3)) if len(v) else dict(n=0)
latency = dict(old_all=dict(ttfw=dist(lat["old"]["ttfw"]), final_latency=dist(lat["old"]["fin"])),
               corrected_all=dict(ttfw=dist(lat["corrected"]["ttfw"]), final_after_end=dist(lat["corrected"]["fin_after_end"]), final_after_flush=dist(lat["corrected"]["fin_after_flush"])),
               mismatch_clips_old=dict(ttfw=dist(lat["mismatch_old"]["ttfw"]), final_latency=dist(lat["mismatch_old"]["fin"])),
               mismatch_clips_corrected=dict(ttfw=dist(lat["mismatch_corr"]["ttfw"]), final_after_flush=dist(lat["mismatch_corr"]["fin_after_flush"])),
               clips_where_index_and_timestamp_pairing_differ=[a["id"] for a in audit if not a["index_pairing_equals_timestamp_pairing"]])

