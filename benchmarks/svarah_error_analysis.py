# ---------------------------------------------------------------- alignment (same tie-break as wer.edit_counts)
def align(ref, hyp):
    n, m = len(ref), len(hyp)
    d = np.zeros((n + 1, m + 1), dtype=np.int32)
    d[:, 0] = np.arange(n + 1)
    d[0, :] = np.arange(m + 1)
    for i in range(1, n + 1):
        for j in range(1, m + 1):
            d[i, j] = min(d[i - 1, j] + 1, d[i, j - 1] + 1, d[i - 1, j - 1] + (ref[i - 1] != hyp[j - 1]))
    i, j, ops = n, m, []
    while i > 0 or j > 0:
        if i > 0 and j > 0 and d[i, j] == d[i - 1, j - 1] + (ref[i - 1] != hyp[j - 1]):
            ops.append(("eq" if ref[i - 1] == hyp[j - 1] else "sub", i - 1, j - 1))
            i, j = i - 1, j - 1
        elif i > 0 and d[i, j] == d[i - 1, j] + 1:
            ops.append(("del", i - 1, None)); i -= 1
        else:
            ops.append(("ins", None, j - 1)); j -= 1
    return ops[::-1]


def counts(ops):
    c = Counter(o[0] for o in ops)
    return dict(sub=c["sub"], dele=c["del"], ins=c["ins"], errors=c["sub"] + c["del"] + c["ins"])


# ---------------------------------------------------------------- normalisation policies (explicit, reproducible)
UNITS = {w: i for i, w in enumerate("zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen seventeen eighteen nineteen".split())}
TENS = {w: 10 * (i + 2) for i, w in enumerate("twenty thirty forty fifty sixty seventy eighty ninety".split())}
SCALES = {"hundred": 100, "thousand": 1000, "lakh": 100000, "lakhs": 100000, "million": 1000000, "crore": 10000000, "crores": 10000000}
DIGITWORDS = {w: UNITS[w] for w in "zero one two three four five six seven eight nine".split()}
NUMW = set(UNITS) | set(TENS) | set(SCALES)


def pre_text(t):
    """Policy C text pre-pass (applied to BOTH sides): 1,000 -> 1000 ; 3.5 -> 3 point 5 ; % -> percent."""
    t = re.sub(r"(?<=\d),(?=\d{3}\b)", "", t)
    t = re.sub(r"(?<=\d)\.(?=\d)", " point ", t)
    return t.replace("%", " percent ")


def parse_cardinal(run):
    total, cur = 0, 0
    for w in run:
        if w == "and":
            continue
        if w in UNITS:
            cur += UNITS[w]
        elif w in TENS:
            cur += TENS[w]
        elif w == "hundred":
            cur = max(cur, 1) * 100
        else:
            total += max(cur, 1) * SCALES[w]; cur = 0
    return str(total + cur)


def num_norm(toks):
    """Policy C token pass. Returns (tokens, provenance) where provenance[k] = list of source token indices.
    1) runs of >=2 single digits (0-9 or zero..nine) -> one digit string
    2) runs of number words (and 'and' strictly between number words) -> integer string"""
    out, prov, i, n = [], [], 0, len(toks)
    isd = lambda t: (len(t) == 1 and t.isdigit()) or t in DIGITWORDS  # noqa: E731
    dval = lambda t: t if t.isdigit() else str(DIGITWORDS[t])  # noqa: E731
    while i < n:
        t = toks[i]
        if isd(t):
            j = i
            while j < n and isd(toks[j]):
                j += 1
            if j - i >= 2:
                out.append("".join(dval(x) for x in toks[i:j])); prov.append(list(range(i, j))); i = j; continue
        if t in NUMW:
            j = i
            while j < n and (toks[j] in NUMW or (toks[j] == "and" and j + 1 < n and toks[j + 1] in NUMW and j > i)):
                j += 1
            run = toks[i:j]
            out.append(parse_cardinal(run)); prov.append(list(range(i, j))); i = j; continue
        out.append(t); prov.append([i]); i += 1
    return out, prov


FILL = {"uh", "um", "umm", "uhh", "uhm", "hmm", "hm", "mm", "mmm", "ah", "er", "erm", "eh", "huh"}


def policy_tokens(ref_t, hyp_t):
    """Returns dict policy -> (ref_tokens, hyp_tokens, ref_prov, hyp_prov)."""
    A = (normalize(ref_t), normalize(hyp_t))
    out = {"A": (A[0], A[1], [[i] for i in range(len(A[0]))], [[i] for i in range(len(A[1]))])}
    out["B"] = out["A"]  # B (case/punct) is already part of A: wer.normalize lowercases and strips punctuation
    rc, rp = num_norm(normalize(pre_text(ref_t)))
    hc, hp = num_norm(normalize(pre_text(hyp_t)))
    out["C"] = (rc, hc, rp, hp)
    # D
    def join(toks, prov, other):
        o = set(other); res, rpv, i = [], [], 0
        while i < len(toks):
            if i + 1 < len(toks) and not toks[i].isdigit() and not toks[i + 1].isdigit():
                j = toks[i] + toks[i + 1]
                if len(j) >= 4 and j in o and j not in toks:
                    res.append(j); rpv.append(prov[i] + prov[i + 1]); i += 2; continue
            res.append(toks[i]); rpv.append(prov[i]); i += 1
        return res, rpv
    r1, rp1 = join(rc, rp, hc)
    h1, hp1 = join(hc, hp, r1)
    r2, rp2 = join(r1, rp1, h1)
    out["D"] = (r2, h1, rp2, hp1)
    # E (supplementary, NOT requested): D + drop filler tokens on both sides
    rf = [(t, p) for t, p in zip(r2, rp2) if t not in FILL]
    hf = [(t, p) for t, p in zip(h1, hp1) if t not in FILL]
    out["E"] = ([t for t, _ in rf], [t for t, _ in hf], [p for _, p in rf], [p for _, p in hf])
    return out


